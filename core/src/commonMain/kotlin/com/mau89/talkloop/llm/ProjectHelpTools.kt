/** Source labels and live Git state are rendered from data, never generated by the LLM. */
internal fun projectHelpResponse(answer: String, call: AgentToolCall): String {
    val git = Json.parseToJsonElement(call.result).jsonObject["git"]
    val state = if (git == null || git == JsonNull) {
        "Git: текущая ветка неизвестна — MCP отключён."
    } else {
        val fields = git.jsonObject
        val head = if (fields["detached"]?.jsonPrimitive?.booleanOrNull == true) "detached HEAD"
            else "ветка ${fields["branch"]?.jsonPrimitive?.content.orEmpty()}"
        "Git · MCP: git_branch\n$head\nCommit: ${fields["commit"]?.jsonPrimitive?.content.orEmpty()}"
    }
    val sources = call.documentSources.orEmpty().mapIndexed { index, hit ->
        "[${index + 1}] ${hit.file} — ${hit.section}"
    }.joinToString("\n")
    return "$answer\n\n$state" + if (sources.isEmpty()) "\n\nВ документации не найдено источников."
        else "\n\nИсточники документации:\n$sources"
}
