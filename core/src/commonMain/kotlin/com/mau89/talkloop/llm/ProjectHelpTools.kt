package com.mau89.talkloop.llm

import kotlinx.serialization.json.*

/** Explicit project route; never uses the cookbook or its task memory. */
class ProjectHelpTools(
    private val retriever: DocumentRetriever,
    private val branch: AgentToolProvider,
    private val mcpEnabled: () -> Boolean = { true },
) : AgentToolProvider {
    override suspend fun callFor(request: String): AgentToolCall? {
        val command = request.trim()
        if (!command.startsWith("/help") || (command.length > 5 && !command[5].isWhitespace())) return null
        val question = command.removePrefix("/help").trim().ifEmpty {
            "Как устроен проект TalkLoop: модули core, app/shared, app/androidApp, app/iosApp, server и cli?"
        }
        require(question.length <= 2000) { "Вопрос после /help должен быть не длиннее 2000 символов." }
        // Fetch current state on every turn; a documented branch can already be stale.
        val liveBranch = if (mcpEnabled()) checkNotNull(branch.callFor("git_branch")) else null
        val found = retriever.search(DocumentSearchRequest(question, strategy = "structural", limit = 5))
        require(found.query == question) { "Индекс вернул другой вопрос." }
        val sources = found.results.single { it.strategy == "structural" }.hits
            .distinctBy { it.chunkId }.take(5)
        val payload = buildJsonObject {
            put("question", question)
            put("git", liveBranch?.let { Json.parseToJsonElement(it.result) } ?: JsonNull)
            put("gitStatus", if (liveBranch == null) "MCP отключён; текущая ветка неизвестна" else "live MCP")
            put("sources", buildJsonArray {
                sources.forEachIndexed { index, hit -> add(buildJsonObject {
                    put("number", index + 1); put("file", hit.file); put("section", hit.section); put("text", hit.text)
                }) }
            })
        }
        return AgentToolCall(
            toolName = "project_help", toolDescription = "Документация и текущая git-ветка проекта",
            inputSchema = """{"type":"object","properties":{"question":{"type":"string"}}}""",
            arguments = buildJsonObject { put("question", question) }.toString(),
            result = payload.toString(), serverName = "TalkLoop · проект", documentSources = sources,
            projectHelp = true,
            steps = liveBranch?.let { listOf(AgentToolStep(it.serverName.orEmpty(), it.toolName, it.arguments, it.result)) }.orEmpty(),
        )
    }
}

